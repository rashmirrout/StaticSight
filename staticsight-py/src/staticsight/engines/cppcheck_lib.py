"""A cppcheck library generated from the project's own contracts.

cppcheck knows `malloc`/`free` but not `pool_alloc`/`pool_release`. Doc comments often say it
("MUST be paired with release_buffer()"), so the pairs are read from them and written to
`<data dir>/cppcheck-project.cfg`, which `--library=` loads. cppcheck then reports leaks of project resources too.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from ..config import Config, workspace_data_dir
from ..core.errors import StaticSightError
from .ctags import FUNCTION_KINDS, try_ctags_for_files
from .rg import rg_search

PAIR_RE = (r"\b(?:paired\s+with|(?:released?|freed?|destroyed|closed?|returned|passed|disposed)\s+"
           r"(?:with|by|using|via|through|to))\s+`?([A-Za-z_]\w*(?:::\w+)*)\s*\(")
_PAIR = re.compile(PAIR_RE, re.IGNORECASE)
_COMMENT = re.compile(r"^\s*(?://|/\*|\*)")
_LOOKAHEAD = 12


@dataclass(frozen=True)
class Pair:
    alloc: str
    release: str
    pointer: bool
    path: str
    line: int


def _names(name: str, scope: str) -> list[str]:
    return [f"{scope}::{name}", name] if scope and "::" not in name else [name]


async def find_pairs(cfg: Config) -> list[Pair]:
    try:
        res = await rg_search(cfg, PAIR_RE, ignore_case=True)
    except StaticSightError:
        return []
    hits = [m for m in res.matches() if _COMMENT.match(m.text)]
    if not hits:
        return []
    tags = await try_ctags_for_files(cfg, sorted({m.path for m in hits}))
    pairs: dict[tuple[str, str], Pair] = {}
    for m in hits:
        pm = _PAIR.search(m.text)
        if not pm:
            continue
        release = pm.group(1)
        nxt = sorted((t for t in tags.get(m.path, []) if t.kind in FUNCTION_KINDS | {"prototype"}
                      and m.line < t.line <= m.line + _LOOKAHEAD), key=lambda t: t.line)
        if not nxt or nxt[0].short_name == release.rsplit("::", 1)[-1]:
            continue
        t = nxt[0]
        key = (t.qualified, release)
        if key not in pairs:
            pairs[key] = Pair(t.qualified, release if "::" in release or not t.scope or t.scope_kind != "namespace"
                              else f"{t.scope}::{release}", "*" in t.return_type, m.path, m.line)
    return sorted(pairs.values(), key=lambda p: (p.alloc, p.release))


def render(pairs: list[Pair]) -> str:
    out = ['<?xml version="1.0"?>', "<!-- Generated by StaticSight from contract comments; do not edit. -->",
           '<def format="2">']
    for p in pairs:
        a_scope, _, a_name = p.alloc.rpartition("::")
        r_scope, _, r_name = p.release.rpartition("::")
        tag = "memory" if p.pointer else "resource"
        out.append(f"  <{tag}>")
        out += [f'    <alloc init="false">{n}</alloc>' if p.pointer else f"    <alloc>{n}</alloc>"
                for n in _names(a_name, a_scope)]
        out += [f"    <dealloc>{n}</dealloc>" for n in _names(r_name, r_scope)]
        out.append(f"  </{tag}>")
    out.append("</def>")
    return "\n".join(out) + "\n"


async def project_library(cfg: Config) -> tuple[Path | None, list[Pair]]:
    """Write (or refresh) the generated library; returns its path and the pairs, or (None, []) when there are none."""
    pairs = await find_pairs(cfg)
    if not pairs:
        return None, []
    try:
        d = workspace_data_dir(cfg)[0]
        p = d / "cppcheck-project.cfg"
        text = render(pairs)
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            d.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")
        return p, pairs
    except OSError:
        return None, []
