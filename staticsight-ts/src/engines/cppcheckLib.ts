import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Config } from "../config.js";
import { workspaceDataDir } from "../config.js";
import { StaticSightError } from "../core/errors.js";
import { FUNCTION_KINDS, tryCtagsForFiles } from "./ctags.js";
import { rgSearch } from "./rg.js";

const PAIR_RE = "\\b(?:paired\\s+with|(?:released?|freed?|destroyed|closed?|returned|passed|disposed)\\s+(?:with|by|using|via|through|to))\\s+`?([A-Za-z_]\\w*(?:::\\w+)*)\\s*\\(";
const PAIR = new RegExp(PAIR_RE, "i");
const COMMENT = /^\s*(?:(?:\/\/)|(?:\/\*)|\*)/;
const LOOKAHEAD = 12;

export interface Pair { alloc: string; release: string; pointer: boolean; path: string; line: number }

function names(name: string, scope: string): string[] {
  return scope && !name.includes("::") ? [scope + "::" + name, name] : [name];
}

export async function findPairs(cfg: Config): Promise<Pair[]> {
  let res;
  try { res = await rgSearch(cfg, PAIR_RE, { ignoreCase: true }); } catch (e) { if (e instanceof StaticSightError) return []; throw e; }
  const hits = res.matches().filter((m) => COMMENT.test(m.text));
  if (!hits.length) return [];
  const tags = await tryCtagsForFiles(cfg, [...new Set(hits.map((m) => m.path))].sort());
  const pairs = new Map<string, Pair>();
  for (const m of hits) {
    const pm = PAIR.exec(m.text);
    if (!pm) continue;
    const release = pm[1];
    const nxt = (tags.get(m.path) ?? []).filter((t) => (FUNCTION_KINDS.has(t.kind) || t.kind === "prototype") && m.line < t.line && t.line <= m.line + LOOKAHEAD).sort((a, b) => a.line - b.line);
    if (!nxt.length || nxt[0].shortName === release.split("::").pop()) continue;
    const t = nxt[0], rel = release.includes("::") || !t.scope || t.scopeKind !== "namespace" ? release : t.scope + "::" + release;
    const key = t.qualified + "\0" + release;
    if (!pairs.has(key)) pairs.set(key, { alloc: t.qualified, release: rel, pointer: t.returnType.includes("*"), path: m.path, line: m.line });
  }
  return [...pairs.values()].sort((a, b) => a.alloc < b.alloc ? -1 : a.alloc > b.alloc ? 1 : a.release < b.release ? -1 : a.release > b.release ? 1 : 0);
}

export function render(pairs: Pair[]): string {
  const out = ['<?xml version="1.0"?>', "<!-- Generated by StaticSight from contract comments; do not edit. -->", '<def format="2">'];
  for (const p of pairs) {
    const ai = p.alloc.lastIndexOf("::"), ri = p.release.lastIndexOf("::");
    const aScope = ai >= 0 ? p.alloc.slice(0, ai) : "", aName = ai >= 0 ? p.alloc.slice(ai + 2) : p.alloc;
    const rScope = ri >= 0 ? p.release.slice(0, ri) : "", rName = ri >= 0 ? p.release.slice(ri + 2) : p.release;
    const tag = p.pointer ? "memory" : "resource";
    out.push("  <" + tag + ">");
    for (const n of names(aName, aScope)) out.push(p.pointer ? '    <alloc init="false">' + n + "</alloc>" : "    <alloc>" + n + "</alloc>");
    for (const n of names(rName, rScope)) out.push("    <dealloc>" + n + "</dealloc>");
    out.push("  </" + tag + ">");
  }
  out.push("</def>");
  return out.join("\n") + "\n";
}

export async function projectLibrary(cfg: Config): Promise<[string | null, Pair[]]> {
  const pairs = await findPairs(cfg);
  if (!pairs.length) return [null, []];
  try {
    const d = workspaceDataDir(cfg)[0], p = join(d, "cppcheck-project.cfg"), text = render(pairs);
    if (!existsSync(p) || readFileSync(p, "utf8") !== text) { mkdirSync(d, { recursive: true }); writeFileSync(p, text, "utf8"); }
    return [p, pairs];
  } catch {
    return [null, []];
  }
}
